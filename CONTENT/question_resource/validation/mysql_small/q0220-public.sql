-- 在独立空 MySQL 8.4 测试库中执行，不得用于正式业务库。
SET NAMES utf8mb4 COLLATE utf8mb4_0900_bin;
SET SESSION sql_mode='ONLY_FULL_GROUP_BY,STRICT_TRANS_TABLES,NO_ENGINE_SUBSTITUTION';
CREATE TABLE `monthly` (`month` VARCHAR(160) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin, `sales` INT);
INSERT INTO `monthly` VALUES
('2026-01',1000),
('2026-02',1500),
('2026-03',1500),
('2026-04',900);
-- 参考解；等价解须从同一初始快照另行运行。
SELECT month,CASE WHEN COUNT(sales) OVER(ORDER BY month ROWS BETWEEN 2 PRECEDING AND CURRENT ROW)=3 THEN ROUND(AVG(sales) OVER(ORDER BY month ROWS BETWEEN 2 PRECEDING AND CURRENT ROW),2) END AS avg3 FROM monthly ORDER BY month;
